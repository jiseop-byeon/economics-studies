      <p>기회비용(機會費用 · opportunity cost)은 여기서는 그 돈을 다른 안전한 곳에 두었을 때 받을 수 있었던 이자이다. 수익이 0이 아니어도 예금 이자보다 낮으면 그 차이를 포기한 것이다. 매몰비용(埋沒費用 · sunk cost)은 이미 지출하여 되돌릴 수 없는 비용을 말한다. 산 가격에 얽매여 다음 결정을 내리면 아직 남은 선택의 기회비용을 놓치게 된다. 위험회피심리(危險回避心理 · risk aversion)가 커진 날에는 가격 변동이 큰 자산이 함께 팔리고, 현금과 단기 국채로 수요가 몰리는 경우가 있다. 디레버리징(deleveraging)은 그와 반대로 빌린 돈을 갚기 위해 자산을 파는 과정이다.</p>
